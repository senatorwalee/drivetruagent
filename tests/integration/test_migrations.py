"""The migrations must build the schema, undo it cleanly, and match the models.

These run against their own empty database inside the test container, so they
do not disturb the migrated database the other tests share.
"""

from collections.abc import Iterator
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import make_url

ALEMBIC_INI = Path(__file__).resolve().parents[2] / "alembic.ini"
SCRATCH_DATABASE = "migration_scratch"


@pytest.fixture
def scratch_database_url(postgres_url: str) -> Iterator[str]:
    """Create an empty database, hand over its URL, and drop it afterwards."""
    # CREATE DATABASE cannot run inside a transaction, hence AUTOCOMMIT.
    admin_engine = create_engine(postgres_url, isolation_level="AUTOCOMMIT")
    with admin_engine.connect() as connection:
        connection.execute(text(f"DROP DATABASE IF EXISTS {SCRATCH_DATABASE}"))
        connection.execute(text(f"CREATE DATABASE {SCRATCH_DATABASE}"))

    url = make_url(postgres_url).set(database=SCRATCH_DATABASE)
    yield url.render_as_string(hide_password=False)

    with admin_engine.connect() as connection:
        connection.execute(text(f"DROP DATABASE {SCRATCH_DATABASE} WITH (FORCE)"))
    admin_engine.dispose()


def alembic_config(database_url: str) -> Config:
    config = Config(str(ALEMBIC_INI))
    config.set_main_option("sqlalchemy.url", database_url)
    return config


def table_names(database_url: str) -> set[str]:
    engine = create_engine(database_url)
    try:
        return set(inspect(engine).get_table_names())
    finally:
        engine.dispose()


def test_upgrade_creates_the_tables(scratch_database_url: str) -> None:
    command.upgrade(alembic_config(scratch_database_url), "head")

    assert table_names(scratch_database_url) == {
        "alembic_version",
        "menu_categories",
        "menu_items",
        "option_groups",
        "options",
        "menu_item_aliases",
        "sessions",
        "carts",
        "cart_lines",
        "cart_line_options",
        "orders",
        "order_lines",
        "order_line_options",
        "pending_actions",
        "agent_events",
    }


def test_downgrade_removes_everything(scratch_database_url: str) -> None:
    config = alembic_config(scratch_database_url)
    command.upgrade(config, "head")

    command.downgrade(config, "base")

    # Alembic keeps its own bookkeeping table; nothing else should remain.
    assert table_names(scratch_database_url) == {"alembic_version"}


def test_upgrade_works_again_after_a_downgrade(scratch_database_url: str) -> None:
    config = alembic_config(scratch_database_url)
    command.upgrade(config, "head")
    command.downgrade(config, "base")

    command.upgrade(config, "head")

    assert "menu_items" in table_names(scratch_database_url)


def test_models_and_migrations_agree(scratch_database_url: str) -> None:
    """Fails if a model was changed without writing a migration for it."""
    config = alembic_config(scratch_database_url)
    command.upgrade(config, "head")

    # Raises AutogenerateDiffsDetected if autogenerate would produce anything.
    command.check(config)
