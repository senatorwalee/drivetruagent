import uuid
from datetime import datetime
from enum import StrEnum

from sqlalchemy import CheckConstraint, DateTime, Enum, MetaData, func, text
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Gives every index and constraint a predictable name, so Alembic can change or
# drop them later. Without this, Postgres invents names that differ per database.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Parent class of every table model."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    # Read database-generated values (ids, timestamps) back as part of the
    # INSERT or UPDATE. Otherwise SQLAlchemy would fetch them lazily on first
    # access, which fails in async code.
    __mapper_args__ = {"eager_defaults": True}  # noqa: RUF012


class UuidPrimaryKey:
    """Adds an `id` column: a UUID generated by the database."""

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=text("gen_random_uuid()"),
        sort_order=-10,
    )


class Timestamps:
    """Adds `created_at` and `updated_at`, both in UTC."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        sort_order=100,
    )
    # Refreshed by SQLAlchemy on each ORM update; raw SQL updates must set it.
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        sort_order=101,
    )


def text_enum(enum_class: type[StrEnum]) -> Enum:
    """A text column that loads as the given enum.

    Chosen over a Postgres enum type because adding or removing a value is
    then an ordinary constraint change in a migration. Pair it with
    `enum_check` in the table's constraints so the database rejects other values.
    """
    return Enum(
        enum_class,
        native_enum=False,
        create_constraint=False,
        length=32,
        values_callable=lambda members: [member.value for member in members],
    )


def enum_check(column: str, enum_class: type[StrEnum]) -> CheckConstraint:
    """Limit a text column to an enum's values."""
    allowed = ", ".join(f"'{member.value}'" for member in enum_class)
    return CheckConstraint(f"{column} IN ({allowed})", name=f"{column}_valid")


def has_english(column: str) -> CheckConstraint:
    """Require a translated-text column to hold an English entry (the fallback).

    A missing key makes `->` return NULL, and a CHECK treats NULL as a pass, so
    the comparison uses IS NOT DISTINCT FROM, which never yields NULL. A column
    that is NULL as a whole is allowed; NOT NULL decides that separately.
    """
    return CheckConstraint(
        f"{column} IS NULL "
        f"OR jsonb_typeof({column} -> 'en') IS NOT DISTINCT FROM 'string'",
        name=f"{column}_has_en",
    )
