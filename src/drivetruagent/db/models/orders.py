"""Submitted orders: a frozen copy of a cart.

Names and prices are copied in at submission. A later menu change, or even
the removal of an item, must never alter what a past order says.
"""

import uuid
from datetime import datetime

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    Identity,
    UniqueConstraint,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from drivetruagent.db.base import (
    Base,
    Timestamps,
    UuidPrimaryKey,
    enum_check,
    text_enum,
)
from drivetruagent.enums import Language


class Order(UuidPrimaryKey, Timestamps, Base):
    __tablename__ = "orders"
    __table_args__ = (
        enum_check("language", Language),
        CheckConstraint("subtotal_cents >= 0", name="subtotal_cents_non_negative"),
        CheckConstraint("tax_cents >= 0", name="tax_cents_non_negative"),
        CheckConstraint(
            "total_cents = subtotal_cents + tax_cents", name="total_matches"
        ),
    )

    # The short number a customer sees. Generated by the database and for
    # display only: lookups use the UUID id, which cannot be guessed.
    order_number: Mapped[int] = mapped_column(Identity(always=True), unique=True)
    # Unique: a session produces at most one order.
    session_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("sessions.id", ondelete="RESTRICT"), unique=True
    )
    # The language the names below were frozen in.
    language: Mapped[Language] = mapped_column(text_enum(Language))
    subtotal_cents: Mapped[int]
    tax_cents: Mapped[int]
    total_cents: Mapped[int]
    submitted_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    lines: Mapped[list["OrderLine"]] = relationship(
        back_populates="order",
        lazy="raise",
        order_by="OrderLine.line_no",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )


class OrderLine(UuidPrimaryKey, Timestamps, Base):
    __tablename__ = "order_lines"
    __table_args__ = (
        # Also serves lookups by order_id, so no separate index is needed.
        UniqueConstraint("order_id", "line_no"),
        CheckConstraint("line_no >= 1", name="line_no_positive"),
        CheckConstraint("quantity >= 1", name="quantity_positive"),
        CheckConstraint("unit_price_cents >= 0", name="unit_price_cents_non_negative"),
        CheckConstraint(
            "line_total_cents = unit_price_cents * quantity",
            name="line_total_matches",
        ),
    )

    order_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("orders.id", ondelete="CASCADE")
    )
    line_no: Mapped[int]
    # Kept for reporting. The code and name beside it are the frozen copy.
    item_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("menu_items.id", ondelete="RESTRICT"), index=True
    )
    item_code: Mapped[str]
    item_name: Mapped[str]
    quantity: Mapped[int]
    # Base price plus the price of every chosen option, at submission time.
    unit_price_cents: Mapped[int]
    line_total_cents: Mapped[int]

    order: Mapped[Order] = relationship(back_populates="lines", lazy="raise")
    options: Mapped[list["OrderLineOption"]] = relationship(
        back_populates="line",
        lazy="raise",
        order_by="OrderLineOption.position",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )


class OrderLineOption(UuidPrimaryKey, Timestamps, Base):
    """A chosen option, frozen.

    There is deliberately no foreign key to `options`: the order must stay
    readable even if the option is later removed from the menu.
    """

    __tablename__ = "order_line_options"
    __table_args__ = (
        # Also serves lookups by order_line_id.
        UniqueConstraint("order_line_id", "group_code", "option_code"),
        CheckConstraint(
            "price_delta_cents >= 0", name="price_delta_cents_non_negative"
        ),
        CheckConstraint("position >= 0", name="position_non_negative"),
    )

    order_line_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("order_lines.id", ondelete="CASCADE")
    )
    # Where this option sits among the line's options, so an order reads back
    # in the same order the customer saw.
    position: Mapped[int]
    group_code: Mapped[str]
    group_name: Mapped[str]
    option_code: Mapped[str]
    option_name: Mapped[str]
    price_delta_cents: Mapped[int]

    line: Mapped[OrderLine] = relationship(back_populates="options", lazy="raise")
