"""The agent's event log: every message, model call, tool call and result."""

import uuid
from typing import Any

from sqlalchemy import BigInteger, ForeignKey, Identity, Index
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from drivetruagent.db.base import (
    Base,
    Timestamps,
    UuidPrimaryKey,
    enum_check,
    text_enum,
)
from drivetruagent.enums import AgentEventKind


class AgentEvent(UuidPrimaryKey, Timestamps, Base):
    """One thing that happened in a conversation.

    The log is the only place a conversation lives. It is read back to build
    the model's context for each turn, and it is the audit trail: what the
    customer said, what the model asked for, and what the backend decided.
    """

    __tablename__ = "agent_events"
    __table_args__ = (
        enum_check("kind", AgentEventKind),
        # Reading a session's events in order is the main query.
        Index("ix_agent_events_session_id_seq", "session_id", "seq"),
    )

    session_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("sessions.id", ondelete="CASCADE")
    )
    # Groups the events of one customer turn.
    turn_id: Mapped[uuid.UUID]
    # Generated by the database, always increasing: the order things happened.
    seq: Mapped[int] = mapped_column(BigInteger, Identity(always=True), unique=True)
    kind: Mapped[AgentEventKind] = mapped_column(text_enum(AgentEventKind))
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB)
